import numpy as np
import pandas as pd
from scipy import stats

dfx = pd.read_csv('variant_5_sample_X.csv')
dfy = pd.read_csv('variant_5_sample_Y.csv')

# --- ИСПРАВЛЕНИЕ: flatten() гарантирует 1D-массив ---
x = dfx.values.astype(float).flatten()
y = dfy.values.astype(float).flatten()

m = len(x)
n = len(y)
alpha = 0.05

# Выборочные средние
mean_x = np.mean(x)
mean_y = np.mean(y)

# Несмещённые дисперсии
s1_sq = np.var(x, ddof=1)
s2_sq = np.var(y, ddof=1)

print("""
  Применение pooled t-критерия требует σ₁² = σ₂².
  Проверяем эту предпосылку формально.

  H₀(F): σ₁² = σ₂²
  H₁(F): σ₁² ≠ σ₂²  (двусторонняя)
""")

# F-статистика: большая дисперсия — в числитель
if s1_sq >= s2_sq:
    F_obs = s1_sq / s2_sq
    df1, df2 = m - 1, n - 1
else:
    F_obs = s2_sq / s1_sq
    df1, df2 = n - 1, m - 1

# Двустороннее p-значение для F-критерия
p_F = 2 * min(stats.f.cdf(F_obs, df1, df2),
               stats.f.sf(F_obs, df1, df2))

F_crit_lo = stats.f.ppf(alpha / 2,   df1, df2)
F_crit_hi = stats.f.ppf(1 - alpha/2, df1, df2)

print(f"  s₁² = {s1_sq:.4f}  (n₁-1 = {m-1} ст.св.)")
print(f"  s₂² = {s2_sq:.4f}  (n₂-1 = {n-1} ст.св.)")
print(f"\n  F_набл = max(s²)/min(s²) = {F_obs:.4f}")
print(f"  Критическая область: F < {F_crit_lo:.4f}  или  F > {F_crit_hi:.4f}")
print(f"  p-значение (F) = {p_F:.4f}")

if p_F > alpha:
    print(f"\n  H₀(F) НЕ ОТВЕРГАЕТСЯ (p = {p_F:.4f} > α = {alpha}).")
    print("    Предположение σ₁² = σ₂² не противоречит данным.")
    print("    Применение pooled t-критерия обосновано.\n")
else:
    print(f"\n  H₀(F) ОТВЕРГАЕТСЯ (p = {p_F:.4f} ≤ α = {alpha}).")
    print("    ВНИМАНИЕ: дисперсии значимо различаются!")
    print("    Следует использовать критерий Уэлча (равные дисперсии")
    print("    не предполагаются), а не pooled t-критерий.\n")

# Объединённая дисперсия
k = m + n - 2
pooled_var = ((m - 1) * s1_sq + (n - 1) * s2_sq) / k
pooled_std = np.sqrt(pooled_var)

# Стандартная ошибка разности средних
se = np.sqrt(pooled_var * (1/m + 1/n))

# Наблюдаемое значение t
t_obs = (mean_x - mean_y) / se

# Критическое значение
t_crit = stats.t.ppf(1 - alpha/2, k)

p_value = 2 * stats.t.sf(abs(t_obs), k)

print("""
1. ПОСТАНОВКА ЗАДАЧИ И ГИПОТЕЗЫ
  Имеются две независимые выборки из нормальных генеральных
  совокупностей с неизвестными, но равными дисперсиями:
    σ₁² = σ₂² = σ² (неизвестное)

  Гипотезы:
    H₀: μ₁ = μ₂  — математические ожидания равны
    H₁: μ₁ ≠ μ₂  — математические ожидания различаются
""")
print(f"  Уровень значимости: α = {alpha}")
print(f"  Объёмы выборок: m = {m}, n = {n}")

print(f"""
2. ВЫБОРОЧНЫЕ СРЕДНИЕ
  x̄ = {mean_x:.4f}
  ȳ = {mean_y:.4f}
  Разность средних: x̄ − ȳ = {mean_x - mean_y:.4f}

  Средние визуально различаются, однако это различие может быть
  объяснено случайными флуктуациями. Для проверки применяем
  двухвыборочный t-критерий.""")

print(f"""
3. НЕСМЕЩЁННЫЕ ВЫБОРОЧНЫЕ ДИСПЕРСИИ
  s₁² = {s1_sq:.4f}
  s₂² = {s2_sq:.4f}

  Дисперсии близки по величине ({s1_sq:.2f} и {s2_sq:.2f}).
  F-критерий (блок 0) не отверг H₀(F), что обосновывает
  применение t-критерия с объединённой оценкой дисперсии.""")

print(f"""
4. ОБЪЕДИНЁННАЯ ОЦЕНКА ДИСПЕРСИИ
    σ̂² = [(m−1)·s₁² + (n−1)·s₂²] / (m + n − 2)
        = [{m-1}·{s1_sq:.4f} + {n-1}·{s2_sq:.4f}] / {k}
        = [{(m-1)*s1_sq:.2f} + {(n-1)*s2_sq:.2f}] / {k}
        = {(m-1)*s1_sq + (n-1)*s2_sq:.2f} / {k}
        = {pooled_var:.4f}

  σ̂  = √{pooled_var:.4f} ≈ {pooled_std:.4f}

  Объединённая оценка использует {k} степеней свободы —
  эффективнее, чем каждая дисперсия по отдельности.""")

print(f"""
5. НАБЛЮДАЕМОЕ ЗНАЧЕНИЕ t-СТАТИСТИКИ
    t_набл = (x̄ − ȳ) / (σ̂ · √(1/m + 1/n))
           = ({mean_x:.4f} − {mean_y:.4f}) / √({pooled_var:.4f} · (1/{m} + 1/{n}))
           = {mean_x - mean_y:.4f} / √({pooled_var:.4f} · {1/m + 1/n:.5f})
           = {mean_x - mean_y:.4f} / √({pooled_var * (1/m + 1/n):.4f})
           = {mean_x - mean_y:.4f} / {se:.4f}
           = {t_obs:.4f}

  При верной H₀ статистика имеет распределение Стьюдента
  с k = m + n − 2 = {k} степенями свободы.

  Отрицательный знак означает лишь x̄ < ȳ. При двусторонней
  проверке используется |t_набл| = {abs(t_obs):.4f}.""")

print(f"""
6. КРИТИЧЕСКАЯ ОБЛАСТЬ
  Для H₁: μ₁ ≠ μ₂ критическая область двусторонняя:
    W = (−∞; −t_крит) ∪ (t_крит; +∞)

  t_крит = t(α/2, k) = t({alpha/2}, {k}) ≈ {t_crit:.4f}

  W = (−∞; −{t_crit:.4f}) ∪ ({t_crit:.4f}; +∞)
  O = [−{t_crit:.4f}; {t_crit:.4f}]  ← область, где H₀ не отвергается

  При k = {k} распределение Стьюдента ≈ стандартному нормальному,
  поэтому t_крит ≈ 1.96, что и наблюдается ({t_crit:.4f}).""")

print(f"""
7. ВЫВОД
  |t_набл| = {abs(t_obs):.4f}
  t_крит   = {t_crit:.4f}
  p-значение = {p_value:.4f}          ← ДОБАВЛЕНО

  Сравнение: |t_набл| = {abs(t_obs):.4f}  {'>' if abs(t_obs) > t_crit else '<'}  t_крит = {t_crit:.4f}
  t_набл {'попадает' if abs(t_obs) > t_crit else 'НЕ попадает'} в критическую область W.""")

if abs(t_obs) > t_crit:
    print(f"""
   H₀ ОТВЕРГАЕТСЯ на уровне значимости α = {alpha}.

  Содержательный вывод: разность средних (x̄ = {mean_x:.4f},
  ȳ = {mean_y:.4f}, Δ = {abs(mean_x - mean_y):.4f}) статистически значима
  (p = {p_value:.4f} < α = {alpha}).
  Есть основания считать, что генеральные совокупности имеют
  разные математические ожидания.""")
else:
    print(f"""
   H₀ НЕ ОТВЕРГАЕТСЯ на уровне значимости α = {alpha}.

  Содержательный вывод: наблюдаемая разность средних
  (x̄ = {mean_x:.4f}, ȳ = {mean_y:.4f}, Δ = {abs(mean_x - mean_y):.4f})
  вполне объясняется случайной выборочной изменчивостью
  при σ̂² = {pooled_var:.4f}. Нет статистически значимых оснований
  утверждать, что математические ожидания двух генеральных
  совокупностей различаются (p = {p_value:.4f} > α = {alpha}).""")